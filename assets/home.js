function renderSample() {
  const playing = Boolean(sample?.started);
  for (const button of sampleButtons) {
    button.disabled = !AudioEngine;
    button.setAttribute('aria-pressed', String(playing));
    button.setAttribute('aria-busy', String(Boolean(sample && !playing)));
  }
  byId('hero-audio-label').textContent = text(playing ? 'sampleStop' : 'samplePlay');
  byId('audio-play-text').textContent = text(playing ? 'audioStop' : 'audioPlay');
  byId('audio-play-icon').textContent = playing ? '■' : '▶';
  byId('hero-audio-hint').textContent = text(!AudioEngine ? 'audioUnsupported' : sampleError ? 'audioFailed' : 'sampleHint');
  document.querySelector('.signal-art').classList.toggle('is-playing', playing);
}

function showSelection() {
  const screen = screens[activeIndex];
  const count = String(activeIndex + 1).padStart(2, '0');
  root.style.setProperty('--accent-rgb', screen.color);
  root.style.setProperty('--accent', screen.colorHex);
  for (const button of screenButtons) {
    const on = button.dataset.screen === screen.id;
    button.classList.toggle('is-active', on);
    button.setAttribute('aria-pressed', String(on));
  }
  byId('selection-text').textContent = screen[language];
  byId('selection-index').textContent = count + ' / 09';
  byId('control-count').firstChild.textContent = count + ' ';
  const music = screen.id === 'music';
  illustration.hidden = !music;
  image.hidden = true;
  if (music) {
    byId('concept-name').textContent = text('musicTitle');
    byId('concept-description').textContent = text('musicDescription');
    captureLabel.textContent = text('musicOverview');
    return;
  }
  image.alt = screen.id === 'welcome' ? text('welcomeAlt') :
    (language === 'pl' ? 'Ekran aplikacji QBINAURAL · ' : 'QBINAURAL app screen · ') + screen.id.toUpperCase();
  captureLabel.textContent = text('originalCapture');
  if (!previewRequested) return;
  const src = gallery[screen.id];
  if (image.getAttribute('src') !== src) image.src = src;
  if (image.complete && image.naturalWidth) {
    image.hidden = false;
  } else {
    captureLabel.textContent = text('previewLoading');
  }
}

