function setLanguage(code) {
  language = code;
  root.lang = code;
  root.dataset.language = code;
  try { localStorage.setItem('qb-language', code); } catch {}
  for (const element of document.querySelectorAll('[data-i18n]')) {
    const value = text(element.dataset.i18n);
    if (value) element.textContent = value;
  }
  for (const button of languageButtons) {
    button.setAttribute('aria-pressed', String(button.dataset.setLanguage === code));
  }
  byId('hero-trust').textContent = text('heroTrust');
  for (const badge of badges) {
    const src = '/assets/app-store-' + code + '.svg';
    if (badge.getAttribute('src') !== src) badge.src = src;
    badge.alt = text('storeBadge');
    badge.nextElementSibling.textContent = badge.alt;
  }
  byId('screen-prev').setAttribute('aria-label', text('previousScreen'));
  byId('screen-next').setAttribute('aria-label', text('nextScreen'));
  nextScreen.setAttribute('aria-label', text('nextScreen'));
  nextScreen.querySelector('.sr-only').textContent = text('nextScreen');
  for (const link of document.querySelectorAll('a[href]')) {
    const href = link.getAttribute('href');
    if (href.startsWith('#')) continue;
    const url = new URL(href, location.href);
    if (url.origin !== location.origin) continue;
    url.searchParams.set('lang', code);
    link.href = url.pathname + url.search + url.hash;
  }
  const url = new URL(location.href);
  if (url.searchParams.has('lang') && url.searchParams.get('lang') !== code) {
    url.searchParams.set('lang', code);
    history.replaceState(history.state, '', url);
  }
  renderSample();
  showSelection();
}
for (const button of languageButtons) button.addEventListener('click', () => setLanguage(button.dataset.setLanguage));
setLanguage(language);

