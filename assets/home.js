function stopSample(immediate = false) {
  const previous = sample;
  sample = null;
  renderSample();
  if (!previous) return;
  clearTimeout(previous.timer);
  const context = previous.context;
  context.onstatechange = null;
  const close = () => { if (context.state !== 'closed') context.close().catch(() => {}); };
  if (immediate || !previous.started || context.state !== 'running') {
    close();
    return;
  }
  const now = context.currentTime;
  previous.output.gain.cancelScheduledValues(now);
  previous.output.gain.setValueAtTime(previous.output.gain.value, now);
  previous.output.gain.linearRampToValueAtTime(0, now + 0.16);
  for (const tone of previous.tones) tone.stop(now + 0.18);
  setTimeout(close, 220);
}

async function toggleSample() {
  if (sample) { stopSample(); return; }
  if (!AudioEngine) return;
  sampleError = false;
  let current;
  try {
    const context = new AudioEngine();
    current = { context, tones: [], started: false, timer: 0 };
    sample = current;
    renderSample();
    const stereo = context.createChannelMerger(2);
    const output = context.createGain();
    current.output = output;
    output.gain.value = 0;
    stereo.connect(output);
    output.connect(context.destination);
    for (const [channel, frequency] of [200, 210].entries()) {
      const tone = context.createOscillator();
      tone.frequency.value = frequency;
      tone.connect(stereo, 0, channel);
      tone.start();
      current.tones.push(tone);
    }
    // Resume from the original tap so Safari can grant audio playback.
    current.timer = setTimeout(() => {
      if (sample === current && !current.started) { sampleError = true; stopSample(true); }
    }, 4500);
    await context.resume();
    if (sample !== current) return;
    clearTimeout(current.timer);
    const now = context.currentTime;
    output.gain.setValueAtTime(0, now);
    output.gain.linearRampToValueAtTime(0.0275, now + 0.35);
    current.started = true;
    context.onstatechange = () => {
      if (sample === current && context.state !== 'running') stopSample(true);
    };
    current.timer = setTimeout(() => stopSample(), 20000);
    renderSample();
  } catch {
    if (!current || sample === current) {
      sampleError = true;
      stopSample(true);
    }
  }
}
